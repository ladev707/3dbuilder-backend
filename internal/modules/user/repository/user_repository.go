// Package userrepository is the only place that runs SQL against the users
// table. It knows nothing about GraphQL, HTTP or business rules; it only
// translates between Go structs and database rows.
package userrepository

import (
	"context"
	"errors"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"

	"github.com/ladev707/3dbuilder-backend/internal/database"
	usermodel "github.com/ladev707/3dbuilder-backend/internal/modules/user/models"
)

// Sentinel errors returned by the repository. The service compares against
// them with errors.Is and converts them into client-safe apperr errors.
var (
	ErrUserNotFound  = errors.New("user not found")
	ErrDuplicateUser = errors.New("username or email already in use")
)

// userColumns is the column list every query selects or returns. scanUser
// reads the columns in exactly this order, so keep the two in sync.
const userColumns = `id, username, email, password_hash, is_active, created_at, updated_at`

// Repository stores users in Postgres.
type Repository struct {
	db *pgxpool.Pool
}

// New creates a Repository that uses the shared connection pool.
func New(db *pgxpool.Pool) *Repository {
	return &Repository{db: db}
}

// List returns one page of non-deleted users matching params.Filter, plus
// the total number of matches (ignoring limit and offset).
func (r *Repository) List(ctx context.Context, params usermodel.ListUsersParams) ([]usermodel.User, int, error) {
	search := database.ContainsPattern(params.Filter.Search)

	// Optional filters without building SQL dynamically: when a parameter is
	// NULL (a nil Go pointer), "$1::text IS NULL" is true and the filter is
	// skipped. The ::text and ::boolean casts tell Postgres the parameter types,
	// which it cannot infer from a bare "IS NULL" check.
	const where = `
		WHERE deleted_at IS NULL
		  AND ($1::text IS NULL OR username ILIKE $1 OR email ILIKE $1)
		  AND ($2::boolean IS NULL OR is_active = $2)`

	// The total is counted separately from the page query. A window function
	// like COUNT(*) OVER() would return no total when offset is past the end.
	var total int
	if err := r.db.QueryRow(ctx, `SELECT COUNT(*) FROM users`+where, search, params.Filter.IsActive).Scan(&total); err != nil {
		return nil, 0, err
	}

	// "id" is a tie-breaker: rows with the same created_at would otherwise
	// come back in an unpredictable order and could repeat across pages.
	rows, err := r.db.Query(ctx, `SELECT `+userColumns+` FROM users`+where+`
		ORDER BY created_at DESC, id
		LIMIT $3 OFFSET $4`, search, params.Filter.IsActive, params.Limit, params.Offset)
	if err != nil {
		return nil, 0, err
	}
	// rows must be closed to return the connection to the pool.
	defer rows.Close()

	// Start from an empty slice, not nil, so an empty page is [] in JSON.
	users := []usermodel.User{}
	for rows.Next() {
		user, err := scanUser(rows)
		if err != nil {
			return nil, 0, err
		}
		users = append(users, user)
	}
	// rows.Err reports errors that happened while iterating.
	return users, total, rows.Err()
}

// FindByID returns a non-deleted user, or ErrUserNotFound.
func (r *Repository) FindByID(ctx context.Context, id uuid.UUID) (usermodel.User, error) {
	row := r.db.QueryRow(ctx, `SELECT `+userColumns+` FROM users WHERE id = $1 AND deleted_at IS NULL`, id)
	return scanUser(row)
}

// Create inserts a user and returns the stored row, including the ID and
// timestamps generated by the database. Returns ErrDuplicateUser when the
// username or email is already used by a non-deleted user.
func (r *Repository) Create(ctx context.Context, user usermodel.User) (usermodel.User, error) {
	// RETURNING gives back the inserted row in the same round trip.
	row := r.db.QueryRow(ctx, `
		INSERT INTO users (username, email, password_hash, is_active)
		VALUES ($1, $2, $3, $4)
		RETURNING `+userColumns, user.Username, user.Email, user.PasswordHash, user.IsActive)
	return scanUser(row)
}

// Update applies the non-nil fields of changes and returns the updated user.
//
// When the password changes or the account ends up inactive, all of the
// user's refresh sessions are revoked in the same transaction, which forces
// them to log in again.
func (r *Repository) Update(ctx context.Context, id uuid.UUID, changes usermodel.UserChanges) (usermodel.User, error) {
	tx, err := r.db.Begin(ctx)
	if err != nil {
		return usermodel.User{}, err
	}
	// Rollback is a no-op after a successful Commit, so deferring it is a safe
	// way to undo everything on any early return.
	defer tx.Rollback(ctx)

	// COALESCE(a, b) returns a unless it is NULL. A nil pointer becomes NULL,
	// so the column keeps its current value: this is a partial update in one
	// static query.
	user, err := scanUser(tx.QueryRow(ctx, `
		UPDATE users SET
			username = COALESCE($2, username),
			email = COALESCE($3, email),
			password_hash = COALESCE($4, password_hash),
			is_active = COALESCE($5, is_active),
			updated_at = NOW()
		WHERE id = $1 AND deleted_at IS NULL
		RETURNING `+userColumns, id, changes.Username, changes.Email, changes.PasswordHash, changes.IsActive))
	if err != nil {
		return usermodel.User{}, err
	}
	if changes.PasswordHash != nil || !user.IsActive {
		if err := revokeSessions(ctx, tx, id); err != nil {
			return usermodel.User{}, err
		}
	}
	return user, tx.Commit(ctx)
}

// Delete soft-deletes a user: the row stays for history, but deleted_at is
// set and every query filters it out. The unique indexes in the migration
// only cover rows WHERE deleted_at IS NULL, so the username and email can be
// registered again. Sessions are revoked so the user is logged out.
func (r *Repository) Delete(ctx context.Context, id uuid.UUID) error {
	tx, err := r.db.Begin(ctx)
	if err != nil {
		return err
	}
	defer tx.Rollback(ctx)

	tag, err := tx.Exec(ctx, `
		UPDATE users SET deleted_at = NOW(), is_active = FALSE, updated_at = NOW()
		WHERE id = $1 AND deleted_at IS NULL`, id)
	if err != nil {
		return err
	}
	// Zero affected rows means the user never existed or was already deleted.
	if tag.RowsAffected() == 0 {
		return ErrUserNotFound
	}
	if err := revokeSessions(ctx, tx, id); err != nil {
		return err
	}
	return tx.Commit(ctx)
}

// revokeSessions invalidates every active refresh token of the user, so
// /auth/user/refresh stops working for them. Access tokens that were already
// issued stay valid until they expire (AUTH_ACCESS_TOKEN_MINUTES).
func revokeSessions(ctx context.Context, tx pgx.Tx, id uuid.UUID) error {
	_, err := tx.Exec(ctx, `
		UPDATE auth_sessions SET revoked_at = NOW()
		WHERE gate = 'user' AND principal_id = $1 AND revoked_at IS NULL`, id)
	return err
}

// scanUser reads one row in userColumns order and translates database errors
// into repository errors.
//
// pgx.Row is an interface satisfied by both a single QueryRow result and the
// rows of a multi-row Query, so one function serves List, FindByID, Create
// and Update. For INSERT/UPDATE ... RETURNING, Postgres errors such as unique
// violations surface here, at Scan time.
func scanUser(row pgx.Row) (usermodel.User, error) {
	var user usermodel.User
	err := row.Scan(
		&user.ID,
		&user.Username,
		&user.Email,
		&user.PasswordHash,
		&user.IsActive,
		&user.CreatedAt,
		&user.UpdatedAt,
	)
	switch {
	case errors.Is(err, pgx.ErrNoRows):
		return usermodel.User{}, ErrUserNotFound
	case database.IsUniqueViolation(err):
		return usermodel.User{}, ErrDuplicateUser
	}
	return user, err
}
